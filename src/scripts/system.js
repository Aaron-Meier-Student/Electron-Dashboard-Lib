const fs = require("fs").promises;
const path = require("path");

const { ipcRenderer } = require("electron");

console.warn = (sigma, ...args) => {
    if (!sigma.includes("Electron")) console.log(sigma, ...args);
};

async function loadStyles() {
    try {
        const files = await fs.readdir(path.resolve(__dirname, "./styles/"));
        for (const file of files) {
            document.head.innerHTML += `<link rel="stylesheet" href="./styles/${file}">`;
        }
    } catch (err) {
        console.error(err);
    }
}

async function loadComponents() {
    try {
        const files = await fs.readdir(
            path.resolve(__dirname, "./components/")
        );
        for (const file of files) {
            await new Promise((resolve, reject) => {
                const script = document.createElement("script");
                script.src = `./components/${file}`;
                script.onload = resolve;
                document.body.appendChild(script);
            });
        }
    } catch (err) {
        console.error(err);
    }
}

async function loadSystem() {
    await loadStyles();
    await loadComponents();

    titleBar(ipcRenderer);
    navigationHandler();

    const script = document.createElement("script");
    script.src = "./client.js";
    document.head.appendChild(script);
}

loadSystem();
